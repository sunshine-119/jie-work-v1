/**
 * 根据日期获取当日情话（按天稳定，同一天展示同一条）
 * offset 用于点击「换一句」时顺序切换
 */
export function getDailySweet(date = new Date(), offset = 0) {
  const day = Math.floor(date.getTime() / (24 * 3600 * 1000));
  return sweetWords[(day + offset) % sweetWords.length];
}

/** 随机取一条 */
export function getRandom(arr) {
  if (!arr || !arr.length) return '';
  return arr[Math.floor(Math.random() * arr.length)];
}
